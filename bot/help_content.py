def _catalog_from_payload(locale: str, payload: dict[str, object]) -> FAQCatalog:
    topics: list[FAQTopic] = []
    for topic_payload in payload.get("topics", ()):
        if not isinstance(topic_payload, dict):
            continue
        questions: list[FAQQuestion] = []
        for question_payload in topic_payload.get("questions", ()):
            if not isinstance(question_payload, dict):
                continue
            questions.append(
                FAQQuestion(
                    id=str(question_payload.get("id") or ""),
                    title=str(question_payload.get("title") or ""),
                    answer=str(question_payload.get("answer") or ""),
                )
            )
        topics.append(
            FAQTopic(
                id=str(topic_payload.get("id") or ""),
                title=str(topic_payload.get("title") or ""),
                questions=tuple(questions),
            )
        )
    return FAQCatalog(
        locale=locale,
        home_title=str(payload.get("home_title") or ""),
        home_intro=str(payload.get("home_intro") or ""),
        support_title=str(payload.get("support_title") or ""),
        support_intro=str(payload.get("support_intro") or ""),
        support_missing_url_text=str(payload.get("support_missing_url_text") or ""),
        topics=tuple(topics),
    )


FAQ_CATALOGS["en"] = _catalog_from_payload("en", EN_FAQ_CONTENT)


def get_faq_catalog(locale: str = "uk") -> FAQCatalog:
    return FAQ_CATALOGS.get(locale) or FAQ_CATALOGS["uk"]


def get_faq_topic(topic_id: str, *, locale: str = "uk") -> FAQTopic | None:
    catalog = get_faq_catalog(locale)
    for topic in catalog.topics:
        if topic.id == topic_id:
            return topic
    return None


def get_faq_question(topic_id: str, question_id: str, *, locale: str = "uk") -> tuple[FAQTopic, FAQQuestion] | None:
    topic = get_faq_topic(topic_id, locale=locale)
    if topic is None:
        return None
    for question in topic.questions:
        if question.id == question_id:
            return topic, question
    return None
